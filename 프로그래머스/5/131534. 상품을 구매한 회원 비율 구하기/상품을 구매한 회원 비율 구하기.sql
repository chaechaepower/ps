SELECT 
    YEAR(S.SALES_DATE) AS YEAR, 
    MONTH(S.SALES_DATE) AS MONTH,
    COUNT(DISTINCT U.USER_ID), 
    ROUND(COUNT(DISTINCT U.USER_ID) / (
        SELECT COUNT(*)
        FROM USER_INFO
        WHERE JOINED LIKE '2021-%'
    ),1)
FROM USER_INFO U
JOIN ONLINE_SALE S
ON U.USER_ID = S.USER_ID
WHERE JOINED LIKE '2021-%'
GROUP BY YEAR(S.SALES_DATE), MONTH(S.SALES_DATE)
ORDER BY YEAR, MONTH;