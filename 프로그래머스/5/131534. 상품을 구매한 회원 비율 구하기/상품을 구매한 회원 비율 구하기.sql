SELECT 
    YEAR(SALES_DATE), 
    MONTH(SALES_DATE),
    COUNT(DISTINCT S.USER_ID) AS PURCHASED_USERS,
    ROUND(
        COUNT(DISTINCT S.USER_ID) /
        (SELECT COUNT(*)
        FROM USER_INFO
        WHERE JOINED LIKE '2021%')
        ,1)
FROM USER_INFO U
JOIN ONLINE_SALE S
ON U.USER_ID = S.USER_ID
WHERE U.JOINED LIKE '2021%'
GROUP BY YEAR(SALES_DATE), MONTH(SALES_DATE)