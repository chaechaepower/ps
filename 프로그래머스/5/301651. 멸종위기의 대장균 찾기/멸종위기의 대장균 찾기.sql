WITH RECURSIVE ECOLI AS(
    SELECT ID, PARENT_ID, 1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT C.ID, C.PARENT_ID, GENERATION + 1
    FROM ECOLI P
    JOIN ECOLI_DATA C
    ON P.ID = C.PARENT_ID
)



SELECT COUNT(*), GENERATION
FROM ECOLI
WHERE ID NOT IN (
    SELECT PARENT_ID
    FROM ECOLI
    WHERE PARENT_ID IS NOT NULL
)
GROUP BY GENERATION;





